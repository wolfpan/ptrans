// 取界面文案：语言缺失回退英语；词条缺失先回退英语再回退键名；{name} 占位符按 params 替换
function t(lang, key, params) {
  const dict = UI_STRINGS[lang] || UI_STRINGS['English'];
  let text = dict[key] !== undefined ? dict[key] : (UI_STRINGS['English'][key] !== undefined ? UI_STRINGS['English'][key] : key);
  if (params) {
    for (const [name, value] of Object.entries(params)) text = text.split(`{${name}}`).join(String(value));
  }
  return text;
}

// 目标语言在界面语言下的显示名
function langLabel(lang, value) {
  const names = LANG_NAMES[lang] || LANG_NAMES['English'];
  return names[value] !== undefined ? names[value] : value;
}